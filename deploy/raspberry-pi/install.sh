#!/usr/bin/env bash
# Log-only Google Play build watcher for a Raspberry Pi (or any Linux box).
#
# - never touches the system Python, never uses sudo / apt / systemd
# - uses the newest /usr/local/bin/python3.N (>= 3.10), or PYTHON=/path/to/python3.x
# - own venv (default ~/storewatchenv), helper script ~/store_watch.sh, logs in ~/logs
# - schedules itself in YOUR user's crontab (skip with NO_CRON=1)
#
# Usage (all optional, defaults shown):
#   PACKAGE=com.naturalmotion.customstreetracer2 COUNTRY=DE SAMPLES=6 EVERY_MIN=30 \
#   VENV_PATH=~/storewatchenv DATA_DIR=~/store-watch LOG_DIR=~/logs \
#   PYTHON=/usr/local/bin/python3.14 REF=<git branch, else install from PyPI> NO_CRON=0 \
#     bash install.sh
set -euo pipefail

PACKAGE="${PACKAGE:-com.naturalmotion.customstreetracer2}"
COUNTRY="${COUNTRY:-DE}"
SAMPLES="${SAMPLES:-6}"
EVERY_MIN="${EVERY_MIN:-30}"
VENV_PATH="${VENV_PATH:-$HOME/storewatchenv}"
DATA_DIR="${DATA_DIR:-$HOME/store-watch}"
LOG_DIR="${LOG_DIR:-$HOME/logs}"
HELPER="${HELPER:-$HOME/store_watch.sh}"
REF="${REF:-}"
NO_CRON="${NO_CRON:-0}"
REPO="Nitro4CSR/mobile-store-scraper"
LOCAL_BIN="${LOCAL_BIN:-/usr/local/bin}"

py_ok() {  # $1 = interpreter; true if it runs and is >= 3.10
  "$1" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' >/dev/null 2>&1
}

pick_python() {
  if [ -n "${PYTHON:-}" ]; then
    py_ok "$PYTHON" && { echo "$PYTHON"; return; }
    echo "PYTHON=$PYTHON is missing or older than 3.10" >&2; return 1
  fi
  # newest python3.N in /usr/local/bin first (self-built interpreters), then the system python3
  local p
  for p in $(ls "$LOCAL_BIN"/python3.* 2>/dev/null | grep -E '/python3\.[0-9]+$' | sort -t. -k2 -n -r); do
    py_ok "$p" && { echo "$p"; return; }
  done
  p="$(command -v python3 || true)"
  if [ -n "$p" ] && py_ok "$p"; then echo "$p"; return; fi
  echo "No Python >= 3.10 found in $LOCAL_BIN or on PATH. Pass PYTHON=/path/to/python3.x" >&2
  return 1
}

mkdir -p "$DATA_DIR" "$LOG_DIR"

# --- venv: reuse if healthy, otherwise create with the picked interpreter -------------------------
if [ -x "$VENV_PATH/bin/python" ] && py_ok "$VENV_PATH/bin/python"; then
  echo "Reusing venv $VENV_PATH ($("$VENV_PATH/bin/python" -V))"
else
  PY="$(pick_python)"
  echo "Creating venv $VENV_PATH with $PY ($("$PY" -V))"
  "$PY" -m venv "$VENV_PATH"
fi
PYTHON_VENV="$VENV_PATH/bin/python"

# --- install the package (PyPI, or a GitHub branch archive - no git needed) ------------------------
if [ -n "$REF" ]; then
  SRC="https://github.com/$REPO/archive/refs/heads/$REF.tar.gz"
else
  SRC="mobile-store-scraper>=0.2.0"
fi
echo "Installing $SRC"
"$PYTHON_VENV" -m pip install -q --upgrade pip
"$PYTHON_VENV" -m pip install -q --upgrade "$SRC"

# --- helper script (same style as the bot scripts: ./store_watch.sh run|report|log|status) ---------
cat > "$HELPER" <<HELPER_EOF
#!/bin/bash
# Generated by mobile-store-scraper deploy/raspberry-pi/install.sh
ACTION="\${1:-run}"
PACKAGE="\${2:-$PACKAGE}"

VENV_PATH="$VENV_PATH"
DATA_DIR="$DATA_DIR"
LOG_DIR="$LOG_DIR"
COUNTRY="$COUNTRY"
SAMPLES="$SAMPLES"
LOCK_FILE="\$DATA_DIR/.store_watch.lock"

PYTHON="\$VENV_PATH/bin/python"
export XDG_CACHE_HOME="\$DATA_DIR/cache"   # Play API sessions live next to the data, not in ~/.cache
mkdir -p "\$LOG_DIR" "\$DATA_DIR"
LOG_FILE="\$LOG_DIR/store_watch_\$(date +%F).log"

run_check() {
  {
    echo "=== \$(date '+%F %T') \$PACKAGE (\$(\$PYTHON -V))"
    "\$PYTHON" -m mobile_store_scraper watch "\$PACKAGE" --state-dir "\$DATA_DIR" \\
        --country "\$COUNTRY" --samples "\$SAMPLES" --always-sample
    echo "=== exit \$?"
  } >> "\$LOG_FILE" 2>&1
}

case "\$ACTION" in
  run)
    if command -v flock >/dev/null; then
      exec 9>"\$LOCK_FILE"; flock -n 9 || { echo "previous check still running" >> "\$LOG_FILE"; exit 0; }
    fi
    run_check ;;
  report) "\$PYTHON" -m mobile_store_scraper report "\$PACKAGE" --state-dir "\$DATA_DIR" ;;
  log)    tail -n 60 "\$LOG_FILE" ;;
  status) crontab -l 2>/dev/null | grep -F "\$0" || echo "not scheduled"; ls -la "\$DATA_DIR" ;;
  *) echo "usage: \$0 run|report|log|status [package]"; exit 1 ;;
esac
HELPER_EOF
chmod +x "$HELPER"
echo "Helper written: $HELPER"

# --- schedule in the user's crontab (idempotent: one line per package) ----------------------------
if [ "$NO_CRON" != "1" ]; then
  LINE="*/$EVERY_MIN * * * * $HELPER run $PACKAGE"
  CURRENT="$(crontab -l 2>/dev/null || true)"          # read everything first ...
  printf '%s\n' "$CURRENT" > "$DATA_DIR/crontab.backup.$(date +%F_%H-%M-%S)"
  NEW="$(printf '%s\n' "$CURRENT" | grep -vF "$HELPER run $PACKAGE" | sed '/^$/d' || true)"
  printf '%s\n%s\n' "$NEW" "$LINE" | sed '/^$/d' | crontab -   # ... then write (other lines kept)
  echo "Scheduled (crontab -l): $LINE   (previous crontab backed up in $DATA_DIR)"
fi

echo "First check now..."
"$HELPER" run "$PACKAGE" || true
"$HELPER" report "$PACKAGE" || true
cat <<DONE

Done.
  Builds seen      : $HELPER report $PACKAGE
  Latest run log   : $HELPER log
  Every observation: $DATA_DIR/$PACKAGE.observations.csv
  Stop watching    : crontab -e   (delete the store_watch.sh line)
DONE
